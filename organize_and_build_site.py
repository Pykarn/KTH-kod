"""
Organize downloaded Canvas files into KTH_KOD/<COURSE>/<category>/ using a
local Ollama model, and build simple HTML pages that link to every file.

SAFE BY DESIGN: this script NEVER deletes anything in KTH_KOD/.
  - New files from Canvas are added.
  - Files you already have (same content, wherever you put them) are left alone.
  - Files you added by hand, moved by hand, or that disappeared from Canvas
    stay where they are and are still listed on the web page.
  - A file that was updated on Canvas replaces the old copy only if you
    have not edited that copy yourself; otherwise the new version is saved
    next to it with a _1, _2 ... suffix.

Prerequisites:
1. Install Ollama: https://ollama.com/download
2. Pull a model:  ollama pull llama3.2      (a bigger one such as
   llama3.1:8b or qwen2.5:7b is noticeably more accurate)
3. Make sure Ollama is running (`ollama serve` if it isn't).
4. Run this AFTER canvas_download.py has filled ./canvas_downloads/.

Run:  pip install requests pypdf      (pypdf is optional but recommended)
      python organize_and_build_site.py

Edit the COURSES list below to choose which course folders to process.
"""

import fnmatch
import hashlib
import html
import json
import os
import re
import shutil
from urllib.parse import quote

import requests

# ----------------------------------------------------------------------
# SETTINGS - edit these
# ----------------------------------------------------------------------

# Only these course folders (inside SOURCE_DIR) will be organized.
COURSES = ["EL1000","SF1930","DD1385"]

SOURCE_DIR = "canvas_downloads"   # where canvas_download.py saved the files
SITE_DIR = "KTH_KOD"              # output folder (the one you push to GitHub)

OLLAMA_MODEL = "llama3.2"
OLLAMA_URL = "http://localhost:11434"

# Give the model the first-page text of PDFs. Filenames like "F4_AF.pdf" say
# little, but the first page ("Lecture 4: Bode Plot") usually settles it.
USE_PDF_PREVIEW = True

# False (recommended): a file that is already in KTH_KOD is never moved, so
#   files you sorted by hand stay put, and re-runs are fast.
# True: files that THIS SCRIPT placed earlier are re-classified and MOVED
#   (never deleted) if the model now picks another category. Files you
#   added or moved yourself are never touched, even with True.
RECLASSIFY = False

# --- Filters: what the script is allowed to sort -----------------------
# Files with these extensions are sorted. Set to None to allow every type.
ALLOWED_EXTENSIONS = {
    # documents
    ".pdf", ".ppt", ".pptx", ".doc", ".docx", ".xls", ".xlsx", ".odt",
    ".txt", ".md", ".tex", ".zip",
    # code and data (MATLAB, Python, Java, notebooks ...)
    ".m", ".mlx", ".mat", ".py", ".ipynb", ".java", ".c", ".cpp", ".h",
    ".hpp", ".go", ".r", ".jl", ".csv", ".json",
    # images (assignment figures, screenshots)
    ".png", ".jpg", ".jpeg", ".gif", ".svg",
}

# Filenames matching any of these patterns are ALWAYS copied, whatever the
# extension (case-insensitive, * = anything). Add your own, e.g. "lab*".
ALWAYS_INCLUDE = ["ex*", "*.m"]

# Download folders starting with "github_" come from GitHub repos that a
# teacher linked (see canvas_download.py). They often contain a whole
# website or code project. Set to False to skip them completely.
INCLUDE_GITHUB_REPOS = True

# Folders that are never entered, and filenames that are never copied.
SKIP_DIR_NAMES = {".git", ".github", "node_modules", "__pycache__"}
SKIP_FILE_NAMES = {"index.html", "download", "preview", ".ds_store", "thumbs.db"}

# category name -> description shown to the model. Change names/descriptions
# freely; the folders and the website follow this dict.
CATEGORIES = {
    "exam": "old exams, exam solutions, tentamen, re-exams, practice exams",
    "lecture": "lecture slides, lecture notes, presentations, 'Lecture N' / 'Föreläsning N'",
    "exercise": "exercise sheets, problem sets, labs, assignments, homework, tutorials, "
                "their solutions, and code for them (MATLAB .m files like ex1.m, notebooks)",
    "literature": "textbooks, book chapters, compendiums, reference sheets, formula sheets, articles",
    "other": "anything that clearly fits none of the above (syllabus, schedules, admin info)",
}

# ----------------------------------------------------------------------

MANIFEST_NAME = ".organize_manifest.json"
GENERATED_MARK = "<!-- generated by organize_and_build_site.py -->"

try:
    from pypdf import PdfReader
except ImportError:
    PdfReader = None


# --- helpers ------------------------------------------------------------

def file_hash(path):
    h = hashlib.sha1()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def wanted(filename):
    """Decide whether a source file should be copied at all."""
    low = filename.lower()
    if any(fnmatch.fnmatch(low, p.lower()) for p in ALWAYS_INCLUDE):
        return True
    if filename.startswith(".") or low in SKIP_FILE_NAMES:
        return False
    if ALLOWED_EXTENSIONS is None:
        return True
    return os.path.splitext(low)[1] in ALLOWED_EXTENSIONS


def site_files(course_out):
    """All files currently in the course's site folder (relative paths)."""
    result = []
    for root, dirs, files in os.walk(course_out):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for f in sorted(files):
            rel = os.path.relpath(os.path.join(root, f), course_out)
            if rel == "index.html" or f.startswith("."):
                continue
            result.append(rel.replace(os.sep, "/"))
    return result


def load_manifest(course_out):
    try:
        with open(os.path.join(course_out, MANIFEST_NAME), encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def save_manifest(course_out, manifest):
    os.makedirs(course_out, exist_ok=True)
    with open(os.path.join(course_out, MANIFEST_NAME), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1, ensure_ascii=False, sort_keys=True)


def unique_path(directory, filename):
    """Never overwrite: add _1, _2 ... if the name is taken."""
    base, ext = os.path.splitext(filename)
    path = os.path.join(directory, filename)
    n = 1
    while os.path.exists(path):
        path = os.path.join(directory, f"{base}_{n}{ext}")
        n += 1
    return path


def write_page(path, title, body_lines):
    """Write an index.html, but never overwrite one we didn't generate."""
    if os.path.exists(path):
        with open(path, encoding="utf-8", errors="ignore") as f:
            old = f.read()
        # Pages from the old version of this script had no marker.
        old_style = old.startswith('<!DOCTYPE html><html><head><meta charset="utf-8"><title>') and (
            "&larr; All courses" in old or "<h1>My Courses</h1>" in old
        )
        if GENERATED_MARK not in old and not old_style:
                print(f"  (kept your own {path}, not overwritten)")
                return
    page = (
        f'<!DOCTYPE html>{GENERATED_MARK}<html><head><meta charset="utf-8">'
        f"<title>{html.escape(title)}</title></head><body>\n"
        + "\n".join(body_lines)
        + "\n</body></html>"
    )
    with open(path, "w", encoding="utf-8") as f:
        f.write(page)


# --- classification -----------------------------------------------------

def pdf_preview(path, max_chars=700):
    """Return the first-page text of a PDF (empty string if unavailable)."""
    if not (USE_PDF_PREVIEW and PdfReader and path.lower().endswith(".pdf")):
        return ""
    try:
        text = PdfReader(path).pages[0].extract_text() or ""
        return re.sub(r"\s+", " ", text).strip()[:max_chars]
    except Exception:
        return ""


def ollama_ready():
    """Check that Ollama is running and the model is installed."""
    try:
        r = requests.get(f"{OLLAMA_URL}/api/tags", timeout=5)
        r.raise_for_status()
        names = [m["name"] for m in r.json().get("models", [])]
        if not any(n == OLLAMA_MODEL or n.startswith(OLLAMA_MODEL + ":") for n in names):
            print(f"Model '{OLLAMA_MODEL}' not found. Run: ollama pull {OLLAMA_MODEL}")
            return False
        return True
    except requests.RequestException as e:
        print(f"Ollama is not reachable at {OLLAMA_URL}: {e}")
        return False


def classify_with_ollama(filename, subfolder, preview):
    """Ask the model for a category. The JSON schema forces one valid value."""
    category_help = "\n".join(f"- {c}: {d}" for c, d in CATEGORIES.items())
    prompt = (
        "You sort university course files (KTH) into folders.\n"
        f"Categories:\n{category_help}\n\n"
        "Hints: 'tenta', 'exam', 'omtenta' => exam. Files named F1, F2, "
        "'lecture', 'föreläsning', 'slides' => lecture. 'ex1', 'ovn', 'övning', "
        "'lab', 'hw', 'problem' => exercise.\n\n"
        f"Filename: {filename}\n"
    )
    if subfolder:
        prompt += f"Original Canvas folder: {subfolder}\n"
    if preview:
        prompt += f"Start of the first page: {preview}\n"
    prompt += "\nChoose the single best category."

    payload = {
        "model": OLLAMA_MODEL,
        "messages": [{"role": "user", "content": prompt}],
        "stream": False,
        "options": {"temperature": 0},
        "format": {
            "type": "object",
            "properties": {"category": {"type": "string", "enum": list(CATEGORIES)}},
            "required": ["category"],
        },
    }
    resp = requests.post(f"{OLLAMA_URL}/api/chat", json=payload, timeout=180)
    resp.raise_for_status()
    answer = json.loads(resp.json()["message"]["content"])["category"]
    return answer if answer in CATEGORIES else "other"


def classify_with_rules(filename, subfolder=""):
    """Keyword fallback, only used if Ollama is unavailable or errors."""
    name = f"{subfolder}/{filename}".lower()
    if re.search(r"exam|tenta|omtenta|kontrollskrivning", name):
        return "exam"
    if re.search(r"lecture|slides|forel|föreläsning|(^|[^a-z])f\d+([^a-z]|$)", name):
        return "lecture"
    if re.search(r"exercise|övning|ovn|lab|assignment|uppgift|homework|problem"
                 r"|(^|[^a-z])ex\d+|\.m$|\.ipynb$", name):
        return "exercise"
    if re.search(r"book|chapter|literature|reading|compendium|kompendium|formula", name):
        return "literature"
    return "other"


def classify(filename, subfolder, src_path, use_ollama):
    if use_ollama:
        try:
            return classify_with_ollama(filename, subfolder, pdf_preview(src_path))
        except (requests.RequestException, KeyError, ValueError) as e:
            print(f"  (Ollama failed for {filename}: {e}; using rules)")
    return classify_with_rules(filename, subfolder)


# --- main work ----------------------------------------------------------

def organize_course(course, use_ollama):
    course_src = os.path.join(SOURCE_DIR, course)
    course_out = os.path.join(SITE_DIR, course)
    if not os.path.isdir(course_src):
        print(f"[skip] {course_src} not found")
        return False

    print(f"\nOrganizing {course}...")
    os.makedirs(course_out, exist_ok=True)
    manifest = load_manifest(course_out)  # source path -> {"dest", "sha1"}

    # Everything already in the site folder, indexed by content.
    by_hash = {}
    for rel in site_files(course_out):
        by_hash.setdefault(file_hash(os.path.join(course_out, rel)), rel)

    stats = {"new": 0, "updated": 0, "moved": 0, "kept": 0, "skipped": 0}
    skipped_exts = {}

    for root, dirs, files in os.walk(course_src):
        dirs[:] = [
            d for d in dirs
            if d not in SKIP_DIR_NAMES
            and not (not INCLUDE_GITHUB_REPOS and d.startswith("github_"))
        ]
        subfolder = os.path.relpath(root, course_src)
        subfolder = "" if subfolder == "." else subfolder
        for filename in sorted(files):
            if not wanted(filename):
                stats["skipped"] += 1
                ext = os.path.splitext(filename)[1].lower() or "(no extension)"
                skipped_exts[ext] = skipped_exts.get(ext, 0) + 1
                continue

            src_path = os.path.join(root, filename)
            src_key = os.path.relpath(src_path, course_src).replace(os.sep, "/")
            sha = file_hash(src_path)
            entry = manifest.get(src_key)

            # 1) Same content already somewhere in the site folder: keep it.
            if sha in by_hash:
                existing = by_hash[sha]
                placed_by_us = bool(entry and entry.get("own") and entry.get("dest") == existing)
                if RECLASSIFY and placed_by_us:
                    category = classify(filename, subfolder, src_path, use_ollama)
                    if existing.split("/")[0] != category:
                        dest_dir = os.path.join(course_out, category)
                        os.makedirs(dest_dir, exist_ok=True)
                        new_path = unique_path(dest_dir, os.path.basename(existing))
                        shutil.move(os.path.join(course_out, existing), new_path)
                        new_rel = os.path.relpath(new_path, course_out).replace(os.sep, "/")
                        print(f"  {filename}  moved  {existing}  ->  {new_rel}")
                        by_hash[sha] = existing = new_rel
                        stats["moved"] += 1
                if placed_by_us:
                    manifest[src_key] = {"dest": existing, "sha1": sha, "own": True}
                else:  # yours (added/moved by hand): remember, never touch
                    manifest[src_key] = {"dest": existing, "sha1": sha, "own": False}
                stats["kept"] += 1
                continue

            # 2) Canvas has a newer version of a file we placed earlier.
            if entry and entry.get("own"):
                old_abs = os.path.join(course_out, entry["dest"])
                if os.path.exists(old_abs) and file_hash(old_abs) == entry["sha1"]:
                    shutil.copy2(src_path, old_abs)  # you never edited it
                    dest_rel = entry["dest"]
                    print(f"  {filename}  updated  {dest_rel}")
                    stats["updated"] += 1
                    manifest[src_key] = {"dest": dest_rel, "sha1": sha, "own": True}
                    by_hash[sha] = dest_rel
                    continue
                # You edited or removed our copy: fall through and add the
                # new version as a separate file instead.

            # 3) New file: classify and copy (never overwriting anything).
            category = classify(filename, subfolder, src_path, use_ollama)
            dest_dir = os.path.join(course_out, category)
            os.makedirs(dest_dir, exist_ok=True)
            dest_path = unique_path(dest_dir, filename)
            shutil.copy2(src_path, dest_path)
            dest_rel = os.path.relpath(dest_path, course_out).replace(os.sep, "/")
            manifest[src_key] = {"dest": dest_rel, "sha1": sha, "own": True}
            by_hash[sha] = dest_rel
            stats["new"] += 1
            print(f"  {filename}  ->  {category}")

    save_manifest(course_out, manifest)
    print(
        f"  new: {stats['new']}, updated: {stats['updated']}, moved: {stats['moved']}, "
        f"already there: {stats['kept']}, skipped by filters: {stats['skipped']}"
    )
    if skipped_exts:
        summary = ", ".join(f"{e} x{n}" for e, n in sorted(skipped_exts.items()))
        print(f"  skipped types: {summary}")
        print("  (add an extension to ALLOWED_EXTENSIONS or a pattern to ALWAYS_INCLUDE to keep them)")
    build_course_page(course)
    return True


def build_course_page(course):
    """List EVERYTHING in the course folder, including files you added yourself."""
    course_out = os.path.join(SITE_DIR, course)
    groups = {}
    for rel in site_files(course_out):
        top = rel.split("/")[0] if "/" in rel else ""
        groups.setdefault(top, []).append(rel)

    order = [c for c in CATEGORIES if c in groups]
    order += sorted(g for g in groups if g not in CATEGORIES and g)
    if "" in groups:
        order.append("")

    lines = [f"<h1>{html.escape(course)}</h1>",
             '<p><a href="../index.html">&larr; All courses</a></p>']
    for group in order:
        files = groups[group]
        title = group.title() if group in CATEGORIES else (group or "Files")
        lines.append(f"<h2>{html.escape(title)} ({len(files)})</h2><ul>")
        for rel in sorted(files, key=str.lower):
            shown = rel[len(group) + 1:] if group else rel
            href = "/".join(quote(p) for p in rel.split("/"))
            lines.append(f'<li><a href="{href}">{html.escape(shown)}</a></li>')
        lines.append("</ul>")
    write_page(os.path.join(course_out, "index.html"), course, lines)


def build_root_index():
    """Link every course folder in SITE_DIR, not only the ones in COURSES."""
    os.makedirs(SITE_DIR, exist_ok=True)
    lines = ["<h1>My Courses</h1><ul>"]
    for name in sorted(os.listdir(SITE_DIR), key=str.lower):
        folder = os.path.join(SITE_DIR, name)
        if name.startswith(".") or not os.path.isdir(folder):
            continue
        if os.path.exists(os.path.join(folder, "index.html")):
            lines.append(f'<li><a href="{quote(name)}/index.html">{html.escape(name)}</a></li>')
        else:
            # Folder you manage yourself: list its files right here.
            files = site_files(folder)
            lines.append(f"<li><details><summary>{html.escape(name)} ({len(files)})</summary><ul>")
            for rel in files:
                href = quote(name) + "/" + "/".join(quote(p) for p in rel.split("/"))
                lines.append(f'<li><a href="{href}">{html.escape(rel)}</a></li>')
            lines.append("</ul></details></li>")
    lines.append("</ul>")
    write_page(os.path.join(SITE_DIR, "index.html"), "My Courses", lines)


def main():
    if not os.path.isdir(SOURCE_DIR):
        print(f"No {SOURCE_DIR}/ folder found. Run canvas_download.py first.")
        return

    use_ollama = ollama_ready()
    if not use_ollama:
        print("Falling back to simple keyword rules for ALL files.\n")

    done = sum(1 for course in COURSES if organize_course(course, use_ollama))

    build_root_index()
    print(f"\nDone. Organized {done} course(s). Nothing was deleted. Site files are in ./{SITE_DIR}/")


if __name__ == "__main__":
    main()